"""Write test/if97_sweep_test.dart: IF97 regions 1, 2 and 4 against CoolProp's
independent IF97 backend (and iapws as a second opinion) at many points."""
import sys
import CoolProp.CoolProp as CP
from iapws import IAPWS97
from iapws.iapws97 import _P23_T
def q(o, a, av, b, bv): return CP.PropsSI(o, a, av, b, bv, 'IF97::Water')
pts = []
for T in [273.16, 280, 300, 350, 400, 450, 500, 550, 600, 623.15, 650, 700, 750, 800, 863.15, 900, 1000, 1073.15]:
    for P in [1e3, 1e4, 1e5, 5e5, 1e6, 3e6, 5e6, 1e7, 1.5e7, 2e7, 2.5e7, 3e7, 5e7, 1e8]:
        r = IAPWS97(T=T, P=P/1e6).region
        if r not in (1, 2):
            continue
        if T > 623.15 and T <= 863.15 and P/1e6 > _P23_T(T):
            continue
        h = q('H','T',T,'P',P); s = q('S','T',T,'P',P); d = q('D','T',T,'P',P); c = q('C','T',T,'P',P)
        i = IAPWS97(T=T, P=P/1e6)
        assert abs(i.h*1e3/h - 1) < 1e-9 and abs(i.v*d - 1) < 1e-9, (T, P)
        pts.append((T, P, h, s, 1/d, c, r))
sat = []
for T in [273.16, 300, 350, 373.15, 400, 450, 500, 550, 600, 623.15]:
    sat.append((T, q('P','T',T,'Q',0)))
for P in [611.657, 1e3, 1e4, 101325, 1e5, 1e6, 4e6, 1e7, 1.2e7, 1.65e7]:
    sat.append((q('T','P',P,'Q',0), P))
w = open(sys.argv[1], 'w')
w.write('''// GENERATED by tool/gen_if97_sweep.py — reference values from the
// CoolProp 8.0 IF97 backend (independent C++ implementation), confirmed
// against the Python iapws 1.5.5 package to 1e-9. Do not edit by hand.
import 'package:flowsheet/tools/if97.dart';
import 'package:flutter_test/flutter_test.dart';

/// (T K, p Pa, h J/kg, s J/kgK, v m3/kg, cp J/kgK, region)
const _pt = <(double, double, double, double, double, double, int)>[
''')
for p in pts: w.write('  (%r, %r, %r, %r, %r, %r, %d),\n' % p)
w.write('];\n\n/// (Tsat K, psat Pa) on the saturation line.\nconst _sat = <(double, double)>[\n')
for p in sat: w.write('  (%r, %r),\n' % p)
w.write('''];

void main() {
  test('IF97 regions 1 and 2 at ${_pt.length} points vs CoolProp IF97', () {
    for (final (t, p, h, s, v, cp, region) in _pt) {
      final st = if97State(t, p);
      final at = 'T=$t K p=$p Pa';
      expect(st.region, region, reason: at);
      expect(st.h, closeTo(h, 1e-9 * h.abs() + 1e-6), reason: 'h $at');
      expect(st.s, closeTo(s, 1e-9 * s.abs() + 1e-6), reason: 's $at');
      expect(st.v, closeTo(v, 1e-9 * v), reason: 'v $at');
      expect(st.cp, closeTo(cp, 1e-8 * cp), reason: 'cp $at');
    }
  });

  test('IF97 region 4 saturation line vs CoolProp IF97', () {
    for (final (t, p) in _sat) {
      expect(if97Psat(t), closeTo(p, 1e-9 * p), reason: 'psat($t)');
      expect(if97Tsat(p), closeTo(t, 1e-7), reason: 'tsat($p)');
    }
  });

  test('IF97 Tables 35 and 36, all points', () {
    for (final (t, p) in [(300.0, 0.353658941e4), (500.0, 0.263889776e7), (600.0, 0.123443146e8)]) {
      expect(if97Psat(t), closeTo(p, 5e-9 * p));
    }
    for (final (p, t) in [(0.1e6, 372.755919), (1e6, 453.035632), (10e6, 584.149488)]) {
      expect(if97Tsat(p), closeTo(t, 5e-7));
    }
    // B23 verification point (release §4): T = 623.15 K ⇄ p = 16.5291643 MPa.
    expect(if97PB23(623.15), closeTo(16.5291643e6, 1));
  });

  test('IF97 range errors outside the implemented regions', () {
    expect(() => if97State(700, 50e6), throwsA(isA<If97RangeError>())); // region 3
    expect(() => if97State(1100, 1e6), throwsA(isA<If97RangeError>())); // region 5
    expect(() => if97State(300, 150e6), throwsA(isA<If97RangeError>()));
  });
}
''')
print(len(pts), 'pt points,', len(sat), 'sat points')
