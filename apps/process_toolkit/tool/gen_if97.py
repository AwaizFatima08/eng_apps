"""Generate lib/tools/if97_data.dart from the iapws package's IF97 tables and
cross-check every coefficient's 14-digit mantissa against the text of the
official IAPWS R7-97(2012) release PDF (pdftotext -layout of IF97-Rev.pdf, passed as argv[1])."""
import re, sys
from decimal import Decimal
import iapws._iapws97Constants as C

txt = open(sys.argv[1]).read()
# mantissas in the PDF look like "0.146 329 712 131 67"
pdf = set()
for m in re.finditer(r'0\.(\d{3}) (\d{3}) (\d{3}) (\d{3}) (\d{2})', txt):
    pdf.add(''.join(m.groups()))

def mant(x):
    d = Decimal(repr(float(x))).copy_abs()
    s = '%.13e' % d  # d.ddddddddddddd e
    digits = s.split('e')[0].replace('.', '')
    return digits[:14]

def check(name, ns):
    bad = [x for x in ns if mant(x) not in pdf]
    print(f'{name}: {len(ns)} coefficients, {len(ns)-len(bad)} found in release PDF', file=sys.stderr)
    for b in bad:
        print('   NOT FOUND', b, mant(b), file=sys.stderr)
    return not bad

r1n = list(C.Region1_n); r1i = list(C.Region1_Li); r1j = list(C.Region1_Lj)
r2n = list(C.Region2_n); r2i = list(C.Region2_Li); r2j = list(C.Region2_Lj)
r2on = list(C.Region2_cp0_no); r2oj = list(C.Region2_cp0_Jo)
r4n = [0.11670521452767E+04, -0.72421316703206E+06, -0.17073846940092E+02,
       0.12020824702470E+05, -0.32325550322333E+07, 0.14915108613530E+02,
       -0.48232657361591E+04, 0.40511340542057E+06, -0.23855557567849E+00,
       0.65017534844798E+03]
b23n = [0.34805185628969e3, -0.11671859879975e1, 0.10192970039326e-2,
        0.57254459862746e3, 0.13918839778870e2]
ok = all([check('Region 1 (Table 2)', r1n), check('Region 2 ideal (Table 10)', r2on),
          check('Region 2 residual (Table 11)', r2n), check('Region 4 (Table 34)', r4n),
          check('B23 (Table 1)', b23n)])
assert len(r1n) == 34 and len(r2n) == 43 and len(r2on) == 9
# exponents of Table 2 / Table 11 checked by the verification tables
def ints(xs): return ', '.join(str(int(x)) for x in xs)
def dbls(xs): return ',\n  '.join(repr(float(x)) for x in xs)
out = f'''// GENERATED by tool/gen_if97.py from the IAPWS-IF97 coefficient tables
// (IAPWS R7-97(2012)); every mantissa cross-checked against the release text.
// Do not edit by hand.

/// Region 1, Table 2: exponents I, J and coefficients n (34 terms).
const List<int> if97R1I = [{ints(r1i)}];
const List<int> if97R1J = [{ints(r1j)}];
const List<double> if97R1N = [
  {dbls(r1n)},
];

/// Region 2 ideal-gas part, Table 10: exponents J° and coefficients n°.
const List<int> if97R2J0 = [{ints(r2oj)}];
const List<double> if97R2N0 = [
  {dbls(r2on)},
];

/// Region 2 residual part, Table 11: exponents I, J and coefficients n (43 terms).
const List<int> if97R2I = [{ints(r2i)}];
const List<int> if97R2J = [{ints(r2j)}];
const List<double> if97R2N = [
  {dbls(r2n)},
];

/// Region 4 saturation line, Table 34: n1 … n10.
const List<double> if97R4N = [
  {dbls(r4n)},
];

/// B23 boundary, Table 1: n1 … n5.
const List<double> if97B23N = [
  {dbls(b23n)},
];
'''
open(sys.argv[2], 'w').write(out)
print('ALL OK' if ok else 'MISMATCH', file=sys.stderr)
