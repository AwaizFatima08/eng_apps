/// Index of the size step containing [mm] (0 < mm ≤ 500).
int isoStepIndex(double mm) {
  for (var i = 0; i < isoSteps.length; i++) {
    if (mm <= isoSteps[i] + 1e-9) return i;
  }
  return -1;
}
